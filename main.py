#!/usr/bin/env python3
"""LinkedIn AI News Post — multi-agent pipeline.

Flow: analytics update → load blog archive (articles.json) → filter out already-published
      → pick random article → write post → publish LinkedIn → notify Telegram.

Source of truth: site/articles.json, the AI Architect blog's append-only archive,
generated by site_pipeline.py. LinkedIn posts always link back to Luca's own blog article.
"""

